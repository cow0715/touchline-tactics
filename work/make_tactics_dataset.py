def players(team, positions):
    return {str(i):[team,x,y] for i,x,y in positions}

def steps(rows):
    return [{"at":t,"ball":ball,"move":{str(i):[x,y] for i,x,y in movements}} for t,ball,*movements in rows]

def lesson(key,side,tag,title,context,question,home,away,opening,space,focus,options,formation="4-3-3"):
    lessons[key]={"side":side,"tag":tag,"title":title,"setup":context,"cue":"이 순간, 어떻게 움직일까요?",
        "question":question,"formation":formation,"space":space,"focus":focus,
        "roster":players("home",home)|players("away",away),"opening":steps(opening),
        "options":[dict(name=name,title=result,why=why,frames=steps(frames),endRoute=route)
                   for name,result,why,frames,route in options]}

